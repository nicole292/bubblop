// Tunes the generated levels (61-560, lib/src/generated_levels.dart).
//
// For each level it tries deals (seeds) until the greedy bot wins some but
// not most attempts. If no deal can be won, it lowers the level's targets
// (scale) by 10% and tries again. It writes the (seed, scale) table to
// lib/src/generated_tuning.dart and one winning move list per level to
// test/generated_solutions.dart (replayed by levels_test.dart).
//
//   cd packages/pop_core
//   dart run tool/generate_levels.dart

import 'dart:io';
import 'dart:math' as math;

import 'package:pop_core/pop_core.dart';

const attempts = 24;
const seedsPerScale = 8;

/// Wanted bot win rate: low (these are the hard levels), but winnable.
/// Breathers (every 5th) may be easier.
(double, double) band(int number) {
  final k = number - GeneratedLevels.first;
  if ((k + 1) % 5 == 0 && (k + 1) % 10 != 0) return (0.2, 0.95);
  return (0.04, 0.6);
}

void main() {
  final tuning = <(int, int, int)>[];
  final solutions = <int, List<int>>{};
  for (var n = GeneratedLevels.first; n <= GeneratedLevels.last; n++) {
    final found = _tune(n);
    if (found == null) {
      stderr.writeln('level $n: no winnable deal found');
      exitCode = 1;
      return;
    }
    final (seed, scale, variant, solution, rate) = found;
    tuning.add((seed, scale, variant));
    solutions[n] = solution;
    final level = GeneratedLevels.build(n, seed: seed, scale: scale, variant: variant);
    stdout.writeln('${n.toString().padLeft(3)}  seed $seed  scale $scale%  v$variant  '
        '${(rate * 100).round().toString().padLeft(3)}%  '
        '${[...level.goals.map((g) => g.text), if (level.drops != null) 'in ${level.drops} drops', if (level.still) 'puzzle', if (level.setup != LevelSetup.normal) '[${level.setup.label}]'].join(' + ')}');
  }

  final table = StringBuffer()
    ..writeln('// Generated by tool/generate_levels.dart. (seed, scale %, variant) for levels 61-560.')
    ..writeln('const generatedTuning = <(int, int, int)>[');
  for (final (seed, scale, variant) in tuning) {
    table.writeln('  ($seed, $scale, $variant),');
  }
  table.writeln('];');
  File('lib/src/generated_tuning.dart').writeAsStringSync(table.toString());

  final out = StringBuffer()
    ..writeln('// Generated by tool/generate_levels.dart. One winning move list (columns,')
    ..writeln('// 0-based) per generated level, replayed by levels_test.dart.')
    ..writeln('const generatedSolutions = <int, List<int>>{');
  solutions.forEach((n, moves) => out.writeln('  $n: [${moves.join(', ')}],'));
  out.writeln('};');
  File('test/generated_solutions.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote lib/src/generated_tuning.dart and test/generated_solutions.dart.');
}

/// Finds a deal, target scale and variant for level [n] whose bot win rate
/// is in its band: too easy raises the targets, unwinnable lowers them, and
/// a variant that can't be won at all makes way for the next one. Falls
/// back to the winnable try closest to the band.
(int, int, int, List<int>, double)? _tune(int n) {
  final (lo, hi) = band(n);
  (int, int, int, List<int>, double)? best;
  double distance(double rate) => rate < lo ? lo - rate : (rate > hi ? rate - hi : 0);
  for (var variant = 0; variant < 6; variant++) {
    var scale = 100;
    final tried = <int>{};
    while (scale >= 40 && scale <= 200 && tried.add(scale)) {
      var easy = 0, winnable = 0;
      for (var i = 0; i < seedsPerScale; i++) {
        final seed = n * 1000 + variant * 211 + scale * 3 + i;
        final level = GeneratedLevels.build(n, seed: seed, scale: scale, variant: variant);
        final (rate, solution) = _winRate(level);
        if (solution == null) continue;
        winnable++;
        if (rate > hi) easy++;
        if (best == null || distance(rate) < distance(best.$5)) best = (seed, scale, variant, solution, rate);
        if (distance(rate) == 0) return best;
      }
      // Mostly too easy: bigger targets. Mostly unwinnable: smaller ones.
      if (winnable > 0 && easy * 2 >= winnable) {
        scale += 20;
      } else {
        scale -= 15;
      }
    }
    if (best != null) return best;
  }
  return best;
}

/// Bot win rate and the shortest winning move list found.
(double, List<int>?) _winRate(LevelDef level) {
  var wins = 0;
  List<int>? best;
  for (var a = 0; a < attempts; a++) {
    final game = level.newGame();
    final tracker = LevelTracker(level);
    final bot = math.Random(level.seed * 1000 + a);
    final moves = <int>[];
    while (!game.isOver && !tracker.complete && game.moves < 1500) {
      final column = _choose(game, bot, noise: a == 0 ? 1 : 40);
      moves.add(column);
      tracker.record(game.drop(column));
    }
    if (tracker.complete) {
      wins++;
      if (best == null || moves.length < best.length) best = moves;
    }
  }
  return (wins / attempts, best);
}

/// The greedy bot from tool/levels.dart.
int _choose(Game game, math.Random random, {required double noise}) {
  final config = game.config;
  final color = game.currentColor;
  var bestColumn = 0;
  var bestValue = double.negativeInfinity;
  for (var col = 0; col < config.columns; col++) {
    if (!game.canDrop(col)) continue;
    final board = game.board;
    final row = board.height(col);
    board.set(col, row, Cell.orb(color));
    final steps = resolveChains(board, config);
    final points = steps.fold(0, (sum, s) => sum + s.points);
    var friends = 0;
    if (steps.isEmpty) {
      for (final (dc, dr) in const [(-1, 0), (1, 0), (0, -1)]) {
        final c = col + dc, r = row + dr;
        if (c < 0 || c >= config.columns || r < 0) continue;
        final n = board.at(c, r);
        if (n != null && n.isOrb && n.color == color) friends++;
      }
    }
    var maxHeight = 0;
    for (var c = 0; c < config.columns; c++) {
      maxHeight = math.max(maxHeight, board.height(c));
    }
    final value = points + friends * 25 - maxHeight * maxHeight * 3 - board.height(col) * 4 +
        random.nextDouble() * noise;
    if (value > bestValue) {
      bestValue = value;
      bestColumn = col;
    }
  }
  return bestColumn;
}
