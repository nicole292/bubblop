// Level calibration. For each campaign level, plays many attempts with a
// noisy greedy bot on the level's fixed deal and reports how often it wins.
// With --tune it searches for a seed whose bot win rate falls in the level's
// difficulty band, prints the seeds to paste into lib/src/levels.dart, and
// writes one winning move list per level to test/level_solutions.dart (the
// test replays them, proving every level can be won).
//
//   cd packages/pop_core
//   dart run tool/levels.dart            (report win rates)
//   dart run tool/levels.dart --tune     (pick seeds, write solutions)
//
// The bot never plans chains, so a human who sets up chains does better on
// chain goals than these rates suggest.

import 'dart:io';
import 'dart:math' as math;

import 'package:pop_core/pop_core.dart';

const attempts = 80;

/// Wanted bot win rate (0–1) per level: near-certain at first, then easing
/// down. Chain ×3 levels get a lower floor (the bot seldom chains).
(double, double) band(LevelDef level) {
  final n = level.number;
  final chain3 = level.goals.any((g) => g.kind == GoalKind.chain && g.target >= 3);
  if (n <= 3) return (0.95, 1.0);
  if (chain3) return n <= 15 ? (0.25, 0.9) : (0.15, 0.8);
  if (n <= 9) return (0.8, 1.0);
  if (n <= 20) return (0.55, 0.95);
  return (0.35, 0.85);
}

void main(List<String> args) {
  final tune = args.contains('--tune');
  final solutions = <int, List<int>>{};
  final seeds = <int, int>{};
  for (final level in Campaign.levels) {
    final (lo, hi) = band(level);
    var seed = level.seed;
    var (rate, solution) = _winRate(level, seed);
    if (tune) {
      for (var tries = 0; tries < 200 && (rate < lo || rate > hi || solution == null); tries++) {
        seed++;
        (rate, solution) = _winRate(LevelDef(level.number, seed, level.goals), seed);
      }
    }
    seeds[level.number] = seed;
    if (solution != null) solutions[level.number] = solution;
    final goals = level.goals.map((g) => g.text).join(' + ');
    final flag = rate < lo || rate > hi ? '  <-- outside ${(lo * 100).round()}–${(hi * 100).round()}%' : '';
    stdout.writeln('${level.number.toString().padLeft(2)}  seed $seed  '
        '${(rate * 100).round().toString().padLeft(3)}%  $goals$flag');
  }
  if (!tune) return;

  stdout.writeln('\nSeeds for lib/src/levels.dart:');
  for (final level in Campaign.levels) {
    stdout.writeln('  ${level.number}: ${seeds[level.number]}');
  }
  final out = StringBuffer()
    ..writeln('// Generated by tool/levels.dart --tune. One winning move list (columns,')
    ..writeln('// 0-based) per campaign level, replayed by levels_test.dart.')
    ..writeln('const levelSolutions = <int, List<int>>{');
  solutions.forEach((n, moves) => out.writeln('  $n: [${moves.join(', ')}],'));
  out.writeln('};');
  File('test/level_solutions.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote test/level_solutions.dart (${solutions.length} levels).');
}

/// Bot win rate on [seed], and the shortest winning move list found.
(double, List<int>?) _winRate(LevelDef level, int seed) {
  var wins = 0;
  List<int>? best;
  for (var a = 0; a < attempts; a++) {
    final game = Game(seed: seed);
    final tracker = LevelTracker(level);
    final bot = math.Random(seed * 1000 + a);
    final moves = <int>[];
    while (!game.isOver && !tracker.complete && game.moves < 3000) {
      final column = _choose(game, bot, noise: a == 0 ? 1 : 40);
      moves.add(column);
      tracker.record(game.drop(column));
    }
    if (tracker.complete) {
      wins++;
      if (best == null || moves.length < best.length) best = moves;
    }
  }
  return (wins / attempts, best);
}

/// The simulator's greedy bot (tool/simulate.dart), with adjustable noise so
/// attempts differ.
int _choose(Game game, math.Random random, {required double noise}) {
  final config = game.config;
  final color = game.currentColor;
  var bestColumn = 0;
  var bestValue = double.negativeInfinity;
  for (var col = 0; col < config.columns; col++) {
    if (!game.canDrop(col)) continue;
    final board = game.board;
    final row = board.height(col);
    board.set(col, row, Cell.orb(color));
    final steps = resolveChains(board, config);
    final points = steps.fold(0, (sum, s) => sum + s.points);
    var friends = 0;
    if (steps.isEmpty) {
      for (final (dc, dr) in const [(-1, 0), (1, 0), (0, -1)]) {
        final c = col + dc, r = row + dr;
        if (c < 0 || c >= config.columns || r < 0) continue;
        final n = board.at(c, r);
        if (n != null && n.isOrb && n.color == color) friends++;
      }
    }
    var maxHeight = 0;
    for (var c = 0; c < config.columns; c++) {
      maxHeight = math.max(maxHeight, board.height(c));
    }
    final value = points + friends * 25 - maxHeight * maxHeight * 3 - board.height(col) * 4 +
        random.nextDouble() * noise;
    if (value > bestValue) {
      bestValue = value;
      bestColumn = col;
    }
  }
  return bestColumn;
}
